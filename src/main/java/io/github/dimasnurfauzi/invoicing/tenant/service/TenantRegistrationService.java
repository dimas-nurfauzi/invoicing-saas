package io.github.dimasnurfauzi.invoicing.tenant.service;

import io.github.dimasnurfauzi.invoicing.tenant.context.TenantContext;
import io.github.dimasnurfauzi.invoicing.tenant.dto.TenantRegistrationRequest;
import io.github.dimasnurfauzi.invoicing.tenant.dto.TenantRegistrationResponse;
import io.github.dimasnurfauzi.invoicing.tenant.entity.Tenant;
import io.github.dimasnurfauzi.invoicing.tenant.exception.SlugAlreadyTakenException;
import io.github.dimasnurfauzi.invoicing.tenant.repository.TenantRepository;
import io.github.dimasnurfauzi.invoicing.user.entity.Role;
import io.github.dimasnurfauzi.invoicing.user.entity.User;
import io.github.dimasnurfauzi.invoicing.user.repository.UserRepository;
import java.util.Locale;
import java.util.UUID;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Service;
import org.springframework.transaction.support.TransactionTemplate;

@Service
public class TenantRegistrationService {

  private final TenantRepository tenants;
  private final UserRepository users;
  private final PasswordEncoder passwordEncoder;
  private final TransactionTemplate transaction;

  public TenantRegistrationService(
      TenantRepository tenants,
      UserRepository users,
      PasswordEncoder passwordEncoder,
      TransactionTemplate transaction) {
    this.tenants = tenants;
    this.users = users;
    this.passwordEncoder = passwordEncoder;
    this.transaction = transaction;
  }

  /**
   * Creates the tenant and its first ADMIN user atomically. Not {@code @Transactional}: the new
   * tenant must be in {@link TenantContext} before the transaction (and Hibernate session) opens,
   * so that {@code @TenantId} fills the admin's tenant_id.
   */
  public TenantRegistrationResponse register(TenantRegistrationRequest request) {
    String slug = request.tenantSlug();
    // Fast path for a friendly error; the unique constraint below is what actually guarantees it.
    if (tenants.existsBySlug(slug)) {
      throw new SlugAlreadyTakenException(slug);
    }

    // Generated by the server, never taken from the request.
    UUID tenantId = UUID.randomUUID();
    String passwordHash = passwordEncoder.encode(request.adminPassword());
    String email = request.adminEmail().trim().toLowerCase(Locale.ROOT);

    return TenantContext.callAs(
        tenantId,
        () ->
            transaction.execute(status -> {
              Tenant tenant;
              try {
                tenant =
                    tenants.saveAndFlush(new Tenant(tenantId, request.tenantName().trim(), slug));
              } catch (DataIntegrityViolationException e) {
                throw new SlugAlreadyTakenException(slug);
              }
              User admin = users.save(new User(email, passwordHash, Role.ADMIN));
              return new TenantRegistrationResponse(
                  tenant.getId(),
                  tenant.getSlug(),
                  admin.getId(),
                  admin.getEmail(),
                  admin.getRole());
            }));
  }
}
